"""Bundle frontend/module_bindings (output of `spacetime generate`) into one block that can sit at the top of the Mana
user_div (imports hoisted to a single versioned esm.sh import; body wrapped so its names cannot collide with app code).
Usage: python tools/embed_bindings.py > /tmp/bind_embed.js  (requires esbuild at /tmp/esb)."""
import re, subprocess, sys, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
subprocess.run(["/tmp/esb/node_modules/.bin/esbuild", R + "/frontend/module_bindings/index.ts", "--bundle", "--format=esm", "--external:spacetimedb", "--outfile=/tmp/bind.js", "--log-level=warning"], check=True)
b = open("/tmp/bind.js").read(); specs = []
def grab(m):
    for sp in m.group(1).split(","):
        sp = sp.strip()
        if sp and sp not in specs: specs.append(sp)
    return ""
body = re.sub(r'import\s*\{([^}]*)\}\s*from\s*"spacetimedb";', grab, b)
body = re.sub(r"export\s*\{[^}]*\};\s*$", "", body.strip())
sys.stdout.write("// SpacetimeDB bindings: generated by `spacetime generate` (spacetime.json -> frontend/module_bindings), bundled by tools/embed_bindings.py\n"
                 "import { " + ", ".join(specs) + " } from 'spacetimedb@2.13.0';\nconst GP_STDB = (() => {\n" + body + "\nreturn { DbConnection, tables, reducers };\n})();\n")
